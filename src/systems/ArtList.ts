/** Как назвать точку картинки (`anchors`) в списке. */
const ANCHOR_NAMES: Record<string, string> = { orb: 'навершие посоха', crystal: 'кристалл посоха' };

/**
 * Список арта для художника, `docs/ART_LIST.md`: таблица по группам с размерами и отметкой готовности.
 * `ready` — имена картинок, которые уже лежат в `public/assets/art`.
 */
export function artList(manifest: ArtConfig, ready: ReadonlySet<string>): string {
  const done = manifest.images.filter((image) => ready.has(image.id)).length;
  const lines = [
    '# Список арта',
    '',
    'Файл собирает `npm run art` из манифеста `src/data/art.json`; руками не править.',
    '',
    `Готово картинок: ${done} из ${manifest.images.length}. Пока картинки нет, на её месте в игре рисунок кодом.`,
    '',
    '## Общие требования',
    '',
    '- Исходник — png, имя и папка как в столбце «Файл», класть в `assets-src/art/`.',
    `- Размер — в пикселях, это ${manifest.scale}× от размера на экране. Исходник может быть крупнее: он уменьшается с сохранением пропорций.`,
    '- Фон прозрачный (кроме фонов уровней). Если прозрачности нет, фон должен быть светлым и ненасыщенным (белая или кремовая бумага): он убирается заливкой от краёв, белое внутри контура остаётся.',
    '- Вырезку котов проверять по `assets-src/art/preview.png`: его пишет тот же `npm run art`.',
    '- Прозрачные края обрезаются, остаток вписывается в размер по центру.',
    '- После добавления файлов: `npm run art`, затем `npm run smoke` и снимки в `screenshots/`.',
  ];

  for (const [group, { title, notes }] of Object.entries(GROUPS)) {
    const images = manifest.images.filter((image) => image.group === group);
    if (images.length === 0) continue;
    const groupDone = images.filter((image) => ready.has(image.id)).length;
    lines.push('', `## ${title} (${groupDone} из ${images.length})`, '', ...notes.map((note) => `- ${note}`), '');
    lines.push('| Файл | Размер | Что нарисовано | Готово |', '| --- | --- | --- | --- |');
    for (const image of images) {
      // Точки, к которым игра привязывает эффекты, — в пикселях картинки.
      const anchors = Object.entries(image.anchors ?? {})
        .map(([name, [x, y]]) => `${ANCHOR_NAMES[name] ?? name} — (${Math.round(x * image.width)}, ${Math.round(y * image.height)})`)
        .join(', ');
      const use = anchors ? `${image.use}; ${anchors} от левого верхнего угла` : image.use;
      lines.push(`| \`${image.file}\` | ${image.width}×${image.height} | ${use} | ${ready.has(image.id) ? 'да' : 'нет'} |`);
    }
  }
  return `${lines.join('\n')}\n`;
}
